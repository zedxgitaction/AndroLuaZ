-- locale.lua - Translation module for AndroLuaZ+
-- Supports: en, zh, es, fr, de, ru, ja, ko, hi, ar, pt, it, tr

local M = {}

-- Current language (default: English)
M.current = "en"

-- Load saved language preference
local function loadLanguage()
  local ok, prefs = pcall(function()
    local path = activity.getLuaExtDir("data") .. "/locale.conf"
    local f = io.open(path, "r")
    if f then
      local lang = f:read("*l")
      f:close()
      if lang and #lang > 0 then
        return lang
      end
    end
    return "en"
  end)
  if ok and prefs then
    M.current = prefs
  end
end

-- Save language preference
function M.setLanguage(lang)
  M.current = lang
  local ok, err = pcall(function()
    local path = activity.getLuaExtDir("data") .. "/locale.conf"
    local f = io.open(path, "w")
    if f then
      f:write(lang)
      f:close()
    end
  end)
end

